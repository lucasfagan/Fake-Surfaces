"""1-skeleta (connected 4-regular multigraphs) in the paper's convention.

A 1-skeleton on n vertices is given by its adjacency matrix A, where a_ij is
the number of edges between vertices i and j and a_ii is twice the number of
loops at vertex i.  D(A) is the integer whose digits are the entries of A
read row by row, i.e. the row-major entries compared lexicographically.

Convention (arXiv:2406.09439, Section 3.1):
* the vertices are ordered so that D(A) is as large as possible;
* the 1-skeleta of complexity n are numbered 1, 2, ... in decreasing D(A);
* the edges are numbered 1..2n in the order of their entry (i, j), i <= j,
  in the upper triangle of A, read left to right and top to bottom.  We
  orient an edge from i to j when i < j; loops (and the order of parallel
  edges) can be chosen freely, and the canonical form below fixes them.
"""

from __future__ import annotations

from functools import lru_cache
from itertools import permutations
from pathlib import Path

Matrix = tuple[tuple[int, ...], ...]


def code(mat, perm) -> tuple[int, ...]:
    n = len(mat)
    return tuple(mat[perm[i]][perm[j]] for i in range(n) for j in range(n))


def is_connected(mat) -> bool:
    n = len(mat)
    seen, stack = {0}, [0]
    while stack:
        i = stack.pop()
        for j in range(n):
            if mat[i][j] and j not in seen:
                seen.add(j)
                stack.append(j)
    return len(seen) == n


TABLE = Path(__file__).resolve().parent.parent / "data" / "one_skeleta.csv"


@lru_cache(maxsize=None)
def skeleta(n: int) -> list[Matrix]:
    """The 1-skeleta of complexity n in the paper's order, read from
    data/one_skeleta.csv (generated by generate_skeleta)."""
    if TABLE.exists():
        rows = [line.strip().split(",") for line in TABLE.read_text().splitlines()[1:]]
        out = [tuple(tuple(int(c) for c in r) for r in m.split())
               for c, k, m in rows if int(c) == n]
        if out:
            return out
    return generate_skeleta(n)


def generate_skeleta(n: int) -> list[Matrix]:
    """All connected 4-regular multigraphs on n vertices, each as its
    D(A)-maximal adjacency matrix, in the paper's order (D(A) decreasing).
    Counts: 1, 2, 4, 10, 28, 97, 359 for n = 1..7."""
    found: set[tuple[int, ...]] = set()
    mat = [[0] * n for _ in range(n)]
    cells = [(i, j) for i in range(n) for j in range(i, n)]

    def fill(c: int) -> None:
        if c == len(cells):
            if all(sum(r) == 4 for r in mat) and is_connected(mat):
                found.add(max(code(mat, p) for p in permutations(range(n))))
            return
        i, j = cells[c]
        room_i = 4 - sum(mat[i])
        room_j = 4 - sum(mat[j])
        top = room_i if i == j else min(room_i, room_j)
        for v in range(top + 1):
            if i == j and v % 2:
                continue
            mat[i][j] = mat[j][i] = v
            last_in_row = j == n - 1
            if not last_in_row or sum(mat[i]) == 4:
                fill(c + 1)
        mat[i][j] = mat[j][i] = 0

    fill(0)
    return [tuple(tuple(c[i * n:(i + 1) * n]) for i in range(n))
            for c in sorted(found, reverse=True)]


def edge_slots(mat: Matrix) -> list[tuple[int, int]]:
    """The endpoint pair (i, j), i <= j, of each edge 1..2n, in order."""
    n = len(mat)
    out = []
    for i in range(n):
        for j in range(i, n):
            out += [(i, j)] * (mat[i][j] // 2 if i == j else mat[i][j])
    return out


def matrix_of_surface(surface) -> list[list[int]]:
    n = surface.complexity
    mat = [[0] * n for _ in range(n)]
    for e in surface.edges:
        a, b = surface.edge_endpoints(e)
        if a == b:
            mat[a][a] += 2
        else:
            mat[a][b] += 1
            mat[b][a] += 1
    return mat


def isomorphisms(mat, target: Matrix) -> list[tuple[int, ...]]:
    """All perm with mat[perm[i]][perm[j]] == target[i][j]: perm[i] is the
    vertex of `mat` placed at position i."""
    n = len(target)
    out = []
    perm: list[int] = []
    used = [False] * n

    def extend(i: int) -> None:
        if i == n:
            out.append(tuple(perm))
            return
        for v in range(n):
            if used[v] or mat[v][v] != target[i][i]:
                continue
            if all(mat[perm[k]][v] == target[k][i] for k in range(i)):
                used[v] = True
                perm.append(v)
                extend(i + 1)
                perm.pop()
                used[v] = False

    extend(0)
    return out


def identify(mat) -> tuple[int, list[tuple[int, ...]]]:
    """(skeleton number, all vertex orderings realizing the canonical
    matrix) for an adjacency matrix of complexity n."""
    n = len(mat)
    sig = sorted(sorted(row) for row in mat)
    for k, target in enumerate(skeleta(n), start=1):
        if sorted(sorted(row) for row in target) != sig:
            continue
        isos = isomorphisms(mat, target)
        if isos:
            return k, isos
    raise ValueError("not a connected 4-regular multigraph")
